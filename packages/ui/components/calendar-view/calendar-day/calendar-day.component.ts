import { CdkDrag, CdkDragPlaceholder, CdkDragPreview } from '@angular/cdk/drag-drop';
import { NgTemplateOutlet } from '@angular/common';
import {
  Component,
  booleanAttribute,
  inject,
  input,
  type InputSignalWithTransform,
  type InputSignal,
} from '@angular/core';
import { NgIcon, provideIcons } from '@ng-icons/core';
import {
  phosphorCaretRightBold,
  phosphorPlusBold,
  phosphorXBold,
} from '@ng-icons/phosphor-icons/bold';

import { CwButton } from '@cadenway/ui/components/button';
import { CwRipple } from '@cadenway/ui/core';
import { CwPopover, CwPopoverClose, CwPopoverTrigger } from '@cadenway/ui/components/popover';

import { CALENDAR_VIEW, type CalendarViewHost, type DayView } from '../calendar-view.token';

/**
 * Component CalendarDayPart
 *
 * @description
 * The content of a day of `cw-calendar-view`, generated by the view inside the day's grid cell (not used on its own): the number and « + » (month view), the lines kept for the bars, the one-day pills, the bars that start that day, and « +n autres » with the day popover. Its own component so the CDK drags it holds find the cell's drop list through the element injector.
 */
@Component({
  selector: 'cw-calendar-view-day',
  imports: [
    CdkDrag,
    CdkDragPlaceholder,
    CdkDragPreview,
    CwButton,
    CwPopover,
    CwPopoverClose,
    CwPopoverTrigger,
    CwRipple,
    NgIcon,
    NgTemplateOutlet,
  ],
  providers: [provideIcons({ phosphorCaretRightBold, phosphorPlusBold, phosphorXBold })],
  host: { class: 'contents' },
  templateUrl: './calendar-day.component.html',
})
export class CalendarDayPart {
  // #region Properties
  /**
   * Property model
   *
   * @description
   * The day as the view computed it.
   *
   * @type {InputSignal<DayView>}
   * @readonly
   */
  public readonly model: InputSignal<DayView> = input.required<DayView>();

  /**
   * Property header
   *
   * @description
   * Draws the number and « + » row (month view).
   *
   * @type {InputSignalWithTransform<boolean, unknown>}
   * @readonly
   */
  public readonly header: InputSignalWithTransform<boolean, unknown> = input(false, {
    transform: booleanAttribute,
  });

  /**
   * Property host
   *
   * @description
   * Calendar view state and actions exposed to the day part.
   *
   * @type {CalendarViewHost}
   * @readonly
   */
  protected readonly host: CalendarViewHost = inject(CALENDAR_VIEW);
  // #endregion
}
