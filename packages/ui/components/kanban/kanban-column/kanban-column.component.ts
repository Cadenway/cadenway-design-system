import { Component, booleanAttribute, computed, inject, input } from '@angular/core';
import { NgIcon, provideIcons } from '@ng-icons/core';
import {
  phosphorArrowsInLineHorizontalBold,
  phosphorArrowsOutLineHorizontalBold,
  phosphorPlusBold,
} from '@ng-icons/phosphor-icons/bold';
import { phosphorWarningCircleFill } from '@ng-icons/phosphor-icons/fill';

import { CwRipple } from '@cadenway/ui/core';
import { CwStatusIcon } from '@cadenway/ui/components/status-icon';

import { KanbanCellPart } from '../kanban-cell/kanban-cell.component';
import { COUNTER, COUNTER_OVER, HEADER_BUTTON } from '../kanban.styles';
import { KANBAN_BOARD, type KanbanColumnView } from '../kanban.token';

/* Literal class strings (Kanban sheet and preview of the Design System artifact). */
type Shape = 'open' | 'target' | 'folded' | 'header' | 'headerFolded';

const HOSTS: Record<Shape, string> = {
  open: 'flex shrink-0 flex-col gap-2 rounded-xl bg-canvas p-2 transition-[width] duration-300 ease-snap motion-reduce:transition-none',
  target:
    'flex shrink-0 flex-col gap-2 rounded-xl bg-canvas bg-linear-to-b from-selected to-selected p-2 transition-[width] duration-300 ease-snap motion-reduce:transition-none',
  folded:
    'flex shrink-0 rounded-xl bg-canvas transition-[width] duration-300 ease-snap motion-reduce:transition-none',
  header: 'flex h-9 shrink-0 items-center gap-2 pr-1.5 pl-3',
  headerFolded: 'flex h-9 shrink-0 items-center justify-center',
};

const FOLDED_BUTTON =
  'relative isolate flex w-full flex-col items-center gap-2.5 overflow-hidden rounded-xl py-2.5 text-sm transition-colors hover:bg-accent outline-hidden focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-ring [&_ng-icon]:[--ng-icon__size:1rem]';

const FOOTER_BUTTON =
  'relative isolate flex h-8 w-full shrink-0 items-center gap-2 overflow-hidden rounded-lg px-2 text-sm text-muted-foreground transition-colors hover:bg-accent hover:text-foreground outline-hidden focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-ring [&_ng-icon]:[--ng-icon__size:1rem]';

/**
 * A column of `cw-kanban`, generated by the board (not used on its own): a `role="group"` named
 * « Colonne En cours » with its header (status icon, name, counter, « + », fold button), the limit
 * alert, the card list, the quick add and the « Ajouter une tâche » footer; or, folded, a 36 px
 * band whose one button unfolds it. With `headerOnly` (swimlanes) it draws the header alone, the
 * lanes drawing the cells. Style hooks: `data-collapsed`, `data-over-limit`, `data-drop-target`.
 */
@Component({
  selector: 'cw-kanban-column',
  imports: [CwRipple, CwStatusIcon, KanbanCellPart, NgIcon],
  providers: [
    provideIcons({
      phosphorArrowsInLineHorizontalBold,
      phosphorArrowsOutLineHorizontalBold,
      phosphorPlusBold,
      phosphorWarningCircleFill,
    }),
  ],
  host: {
    role: 'group',
    '[attr.aria-label]': 'model().groupLabel',
    '[class]': 'hostClass()',
    '[style.width.px]': 'model().collapsed ? 36 : model().width',
    '[attr.data-collapsed]': 'model().collapsed ? "" : null',
    '[attr.data-over-limit]': 'model().over ? "" : null',
    '[attr.data-drop-target]': 'model().target ? "" : null',
  },
  templateUrl: './kanban-column.component.html',
})
export class KanbanColumnPart {
  /** The column as the board computed it. */
  readonly model = input.required<KanbanColumnView>();
  /** Draws the header only (swimlanes). */
  readonly headerOnly = input(false, { transform: booleanAttribute });

  protected readonly board = inject(KANBAN_BOARD);
  protected readonly headerButton = HEADER_BUTTON;
  protected readonly foldedButton = FOLDED_BUTTON;
  protected readonly footerButton = FOOTER_BUTTON;

  protected readonly hostClass = computed(() => {
    const model = this.model();
    if (this.headerOnly()) return HOSTS[model.collapsed ? 'headerFolded' : 'header'];
    if (model.collapsed) return HOSTS.folded;
    return HOSTS[model.target ? 'target' : 'open'];
  });

  protected readonly counterClass = computed(() => (this.model().over ? COUNTER_OVER : COUNTER));

  protected readonly showFooter = computed(() => {
    const cell = this.model().cell;
    return !this.board.readonly() && cell !== null && cell.cards.length > 0 && !cell.quickAdd;
  });
}
