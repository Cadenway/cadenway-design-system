import { CdkDrag, CdkDragPlaceholder, CdkDragPreview, CdkDropList } from '@angular/cdk/drag-drop';
import { NgTemplateOutlet } from '@angular/common';
import {
  Component,
  booleanAttribute,
  computed,
  inject,
  input,
  type InputSignalWithTransform,
  type InputSignal,
  type Signal,
} from '@angular/core';
import { NgIcon, provideIcons } from '@ng-icons/core';
import { phosphorPlusBold, phosphorTrayBold } from '@ng-icons/phosphor-icons/bold';

import { CwButton } from '@cadenway/ui/components/button';

import { KanbanQuickAddPart } from '../kanban-quick-add/kanban-quick-add.component';
import { CARD_BASE, CARD_DENSITIES, CARD_TONES, INDICATORS, PREVIEW } from '../kanban.styles';
import {
  KANBAN_BOARD,
  type KanbanBoard,
  type KanbanCardView,
  type KanbanCellView,
} from '../kanban.token';

/* Literal class strings (Kanban sheet, "Mouvement"): the neighbours make room in 300 ms while a
   card is dragged, and a dropped card glides to its place; nothing moves under reduced motion. */
/**
 * Constant LIST
 *
 * @description
 * Classes for a card drop list.
 *
 * @type {string}
 */
const LIST: string =
  'flex min-h-0 flex-1 flex-col overflow-y-auto ' +
  '[&.cdk-drop-list-dragging>.cdk-drag:not(.cdk-drag-preview)]:transition-transform [&.cdk-drop-list-dragging>.cdk-drag:not(.cdk-drag-preview)]:duration-300 [&.cdk-drop-list-dragging>.cdk-drag:not(.cdk-drag-preview)]:ease-snap ' +
  'motion-reduce:[&.cdk-drop-list-dragging>.cdk-drag]:transition-none';

/**
 * Constant LIST_GAPS
 *
 * @description
 * Spacing classes by card density.
 *
 * @type {{ readonly detailed: "gap-2"; readonly compact: "gap-1.5"; }}
 */
const LIST_GAPS: { readonly detailed: 'gap-2'; readonly compact: 'gap-1.5' } = {
  detailed: 'gap-2',
  compact: 'gap-1.5',
} as const;

/**
 * Constant ITEM
 *
 * @description
 * Classes for draggable card wrappers.
 *
 * @type {string}
 */
const ITEM: string =
  'block [&.cdk-drag-animating]:transition-transform [&.cdk-drag-animating]:duration-300 [&.cdk-drag-animating]:ease-snap motion-reduce:[&.cdk-drag-animating]:transition-none';

/**
 * Constant TARGET
 *
 * @description
 * Classes for a cell drop target.
 *
 * @type {string}
 */
const TARGET: string = 'rounded-lg bg-linear-to-b from-selected to-selected';

/**
 * Component KanbanCellPart
 *
 * @description
 * The drop list of a column (without swimlanes) or of a column × lane cell of `cw-kanban`, generated by the board: a `role="list"` of cards, each a `listitem` holding the focusable `article` frame and the consumer's card template, with the CDK placeholder (line or ghost) and the lifted preview (`aria-hidden`). In a column it also draws the empty state, the ghost of an empty column during a drag, and the quick add.
 */
@Component({
  selector: 'cw-kanban-cell',
  imports: [
    CdkDrag,
    CdkDragPlaceholder,
    CdkDragPreview,
    CdkDropList,
    CwButton,
    KanbanQuickAddPart,
    NgIcon,
    NgTemplateOutlet,
  ],
  providers: [provideIcons({ phosphorPlusBold, phosphorTrayBold })],
  host: {
    '[class]': 'hostClass()',
    '[attr.data-drop-target]': 'cell().target ? "" : null',
  },
  templateUrl: './kanban-cell.component.html',
})
export class KanbanCellPart {
  // #region Properties
  /**
   * Property cell
   *
   * @description
   * The cell as the board computed it.
   *
   * @type {InputSignal<KanbanCellView>}
   * @readonly
   */
  public readonly cell: InputSignal<KanbanCellView> = input.required<KanbanCellView>();

  /**
   * Property inLane
   *
   * @description
   * A cell of a swimlane: no empty state, the target veil on the cell itself.
   *
   * @type {InputSignalWithTransform<boolean, unknown>}
   * @readonly
   */
  public readonly inLane: InputSignalWithTransform<boolean, unknown> = input(false, {
    transform: booleanAttribute,
  });

  /**
   * Property board
   *
   * @description
   * Board state and handlers exposed to this part.
   *
   * @type {KanbanBoard}
   * @readonly
   */
  protected readonly board: KanbanBoard = inject(KANBAN_BOARD);

  /**
   * Property item
   *
   * @description
   * Classes for draggable card wrappers.
   *
   * @type {string}
   * @readonly
   */
  protected readonly item: string = ITEM;

  /**
   * Property emptyGhost
   *
   * @description
   * Classes for the empty-cell drop placeholder.
   *
   * @type {Signal<string>}
   * @readonly
   */
  protected readonly emptyGhost: Signal<string> = computed(() => {
    const ghost:
      | 'h-24 shrink-0 rounded-xl border-2 border-dashed border-line-control'
      | 'h-[34px] shrink-0 rounded-lg border-2 border-dashed border-line-control' =
      this.board.density() === 'compact' ? INDICATORS.ghostCompact : INDICATORS.ghostDetailed;
    return `pointer-events-none absolute inset-x-0 top-0 ${ghost}`;
  });

  /**
   * Property hostClass
   *
   * @description
   * Classes for the current cell or column state.
   *
   * @type {Signal<string>}
   * @readonly
   */
  protected readonly hostClass: Signal<string> = computed(() =>
    this.inLane() && this.cell().target ? `relative ${TARGET}` : 'relative',
  );

  /**
   * Property listClass
   *
   * @description
   * Classes for the card list at the current density.
   *
   * @type {Signal<string>}
   * @readonly
   */
  protected readonly listClass: Signal<string> = computed(
    () => `${LIST} ${LIST_GAPS[this.board.density()]}`,
  );

  /**
   * Property previewClass
   *
   * @description
   * Classes for the drag preview.
   *
   * @type {Signal<string>}
   * @readonly
   */
  protected readonly previewClass: Signal<string> = computed(
    () => `${PREVIEW} ${CARD_DENSITIES[this.board.density()]}`,
  );
  // #endregion

  // #region Methods
  /**
   * Method cardClass
   *
   * @description
   * Builds classes for a card based on its state.
   *
   * @param {KanbanCardView} card - Card involved in the interaction.
   * @returns {string} Classes for the card.
   */
  protected cardClass(card: KanbanCardView): string {
    const tone: 'grabbed' | 'selected' | 'dimmed' | 'rest' = card.grabbed
      ? 'grabbed'
      : card.selected
        ? 'selected'
        : card.dimmed
          ? 'dimmed'
          : 'rest';
    return `${CARD_BASE} ${CARD_DENSITIES[this.board.density()]} ${CARD_TONES[tone]}`;
  }
  // #endregion
}
