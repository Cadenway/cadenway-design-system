import { NgTemplateOutlet } from '@angular/common';
import { Component, computed, inject, input, type InputSignal, type Signal } from '@angular/core';
import { NgIcon, provideIcons } from '@ng-icons/core';
import { phosphorCaretDownBold } from '@ng-icons/phosphor-icons/bold';

import { CwRipple } from '@cadenway/ui/core';

import { KanbanCellPart } from '../kanban-cell/kanban-cell.component';
import { COUNTER } from '../kanban.styles';
import { KANBAN_BOARD, type KanbanBoard, type KanbanLaneView } from '../kanban.token';

/* Literal class strings (Kanban sheet and preview of the Design System artifact): the lane folds
   with the shared collapsible motion, `grid-rows-[0fr]` ↔ `grid-rows-[1fr]` with a fade, 300 ms. */
/**
 * Constant HEADER
 *
 * @description
 * Classes for a swimlane header.
 *
 * @type {string}
 */
const HEADER: string =
  'relative isolate flex h-8 w-full items-center gap-2 overflow-hidden border-t px-2.5 text-left text-sm transition-colors hover:bg-accent outline-hidden focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-ring [&_ng-icon]:[--ng-icon__size:0.875rem]';

/**
 * Constant CHEVRONS
 *
 * @description
 * Chevron classes by lane state.
 *
 * @type {{ readonly open: "shrink-0 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none"; readonly closed: "shrink-0 -rotate-90 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none"; }}
 */
const CHEVRONS: {
  readonly open: 'shrink-0 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none';
  readonly closed: 'shrink-0 -rotate-90 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none';
} = {
  open: 'shrink-0 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none',
  closed:
    'shrink-0 -rotate-90 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none',
} as const;

/**
 * Constant BODIES
 *
 * @description
 * Body classes by lane state.
 *
 * @type {{ readonly open: "grid grid-rows-[1fr] opacity-100 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none"; readonly closed: "grid grid-rows-[0fr] opacity-0 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none"; }}
 */
const BODIES: {
  readonly open: 'grid grid-rows-[1fr] opacity-100 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none';
  readonly closed: 'grid grid-rows-[0fr] opacity-0 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none';
} = {
  open: 'grid grid-rows-[1fr] opacity-100 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none',
  closed:
    'grid grid-rows-[0fr] opacity-0 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none',
} as const;

/**
 * Component KanbanLanePart
 *
 * @description
 * A swimlane of `cw-kanban`, generated by the board: a full-width header button (chevron, marker, label, counter; `aria-expanded`) that folds the lane, then one cell per column, aligned on the column bands. Left and Right on the header fold and unfold the lane; a folded lane is `inert`. Style hook: `data-state="open|closed"` on the host.
 */
@Component({
  selector: 'cw-kanban-lane',
  imports: [CwRipple, KanbanCellPart, NgIcon, NgTemplateOutlet],
  providers: [provideIcons({ phosphorCaretDownBold })],
  host: {
    class: 'block',
    '[attr.data-state]': 'state()',
  },
  templateUrl: './kanban-lane.component.html',
})
export class KanbanLanePart {
  // #region Properties
  /**
   * Property model
   *
   * @description
   * The lane as the board computed it.
   *
   * @type {InputSignal<KanbanLaneView>}
   * @readonly
   */
  public readonly model: InputSignal<KanbanLaneView> = input.required<KanbanLaneView>();

  /**
   * Property board
   *
   * @description
   * Board state and handlers exposed to this part.
   *
   * @type {KanbanBoard}
   * @readonly
   */
  protected readonly board: KanbanBoard = inject(KANBAN_BOARD);

  /**
   * Property header
   *
   * @description
   * Classes for the lane header.
   *
   * @type {string}
   * @readonly
   */
  protected readonly header: string = HEADER;

  /**
   * Property counter
   *
   * @description
   * Classes for the lane count.
   *
   * @type {string}
   * @readonly
   */
  protected readonly counter: string = COUNTER;

  /**
   * Property state
   *
   * @description
   * Current open or closed lane state.
   *
   * @type {Signal<"open" | "closed">}
   * @readonly
   */
  protected readonly state: Signal<'open' | 'closed'> = computed(() =>
    this.model().collapsed ? 'closed' : 'open',
  );

  /**
   * Property chevron
   *
   * @description
   * Chevron classes for the lane state.
   *
   * @type {Signal<"shrink-0 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none" | "shrink-0 -rotate-90 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none">}
   * @readonly
   */
  protected readonly chevron: Signal<
    | 'shrink-0 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none'
    | 'shrink-0 -rotate-90 text-muted-foreground transition-transform duration-300 ease-snap motion-reduce:transition-none'
  > = computed(() => CHEVRONS[this.state()]);

  /**
   * Property body
   *
   * @description
   * Body classes for the lane state.
   *
   * @type {Signal<"grid grid-rows-[1fr] opacity-100 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none" | "grid grid-rows-[0fr] opacity-0 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none">}
   * @readonly
   */
  protected readonly body: Signal<
    | 'grid grid-rows-[1fr] opacity-100 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none'
    | 'grid grid-rows-[0fr] opacity-0 transition-[grid-template-rows,opacity] duration-300 ease-snap motion-reduce:transition-none'
  > = computed(() => BODIES[this.state()]);
  // #endregion

  // #region Methods
  /**
   * Method onKeydown
   *
   * @description
   * Handles keyboard folding of a lane.
   *
   * @param {KeyboardEvent} event - Mouse, keyboard, drag or form event.
   */
  protected onKeydown(event: KeyboardEvent): void {
    const collapsed: boolean = this.model().collapsed;
    if ((event.key === 'ArrowLeft' && !collapsed) || (event.key === 'ArrowRight' && collapsed)) {
      event.preventDefault();
      this.board.toggleLane(this.model().lane.id);
    }
  }
  // #endregion
}
