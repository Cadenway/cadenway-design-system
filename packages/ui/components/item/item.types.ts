/**
 * Type CwItemVariant
 *
 * @description
 * Look of an item: no frame, a `border` frame for an isolated item, `muted` for a soft highlight.
 *
 * @type {'default' | 'outline' | 'muted'}
 */
export type CwItemVariant = 'default' | 'outline' | 'muted';

/**
 * Type CwItemSize
 *
 * @description
 * Spacing of an item and size of its media: 60 px with a description, 40 px, 32 px.
 *
 * @type {'default' | 'sm' | 'xs'}
 */
export type CwItemSize = 'default' | 'sm' | 'xs';

/**
 * Type CwItemMediaVariant
 *
 * @description
 * Shape of the media of an item: free content (an avatar), an icon tile, an image.
 *
 * @type {'default' | 'icon' | 'image'}
 */
export type CwItemMediaVariant = 'default' | 'icon' | 'image';
